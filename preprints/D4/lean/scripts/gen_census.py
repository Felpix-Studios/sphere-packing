"""Generate exact integer census data; Lean checks the finite inequalities.
This does not certify the analytic bridge from kernel energy to these formulas.
"""
import argparse,json,math
from fractions import Fraction as Q
from pathlib import Path
P=Path(__file__).resolve().parents[2]
REF=P/'verify/stage2_origin/reference'
def read(p):return json.loads(p.read_text())
proj=read(P/'verify/stage2_origin/source/target625/origin_completion/ACCEPTED_JOINT_COUNT_PROJECTION.json')
total=list(map(Q,proj['projection_plus_existing_count_coefficients']))
pure=list(map(Q,proj['projection_quadratic_coefficients']))
assert len(total)==len(pure)==21
counts=[t-p for t,p in zip(total,pure)]
planes=[[Q(r['constant'])]+list(map(Q,r['affine_count_coefficients'])) for r in read(REF/'RADIAL_PLANES.json')]
assert len(planes)==12 and all(len(x)==6 for x in planes)
angular=[read(REF/f'ANGULAR_{i}.json') for i in range(3)]
W=Q(angular[0]['accepted_combination']['positive_normalization'])
B=Q(angular[0]['accepted_combination']['weighted_accepted_B'])
def surplus(N,j):
 out=[Q(0)]
 for i,r in enumerate(angular):
  if i!=1 and (N!=r['fixed_count'] or j>r['condition_radius_index']+1):continue
  assert Q(r['accepted_combination']['positive_normalization'])==W
  assert Q(r['accepted_combination']['weighted_accepted_B'])==B
  eps=Q(r['repair']['scale']);eta=Q(r['repair']['pair_shift']);raw=Q(r['raw_B'])
  repaired=Q(r['normalized_B'] if i==1 else r['B'])
  out += [N*(B-W*repaired), N*B-W*(N*raw+eta*N*(N-1)+eps*N*(N-1)*(N-2))]
 return max(out)
floors=[Q(0)]*135; surpluses=[Q(0)]*135
rows=read(P/'data/census_floors.json')['profile']
assert len(rows)==124
for r in rows:
 N=r['N'];j=r['first_radius'];idx=5*N+j-1
 assert type(N)is int and type(j)is int and 0<=N<=26 and 1<=j<=5
 # Same outward rounding used by Ledger.lean: floor to a 10^-24 grid.
 q=Q(r['new_floor']);floors[idx]=Q((q*10**24).__floor__(),10**24)
 surpluses[idx]=surplus(N,j)
D=math.lcm(*(q.denominator for row in [total,counts,*planes,floors,surpluses] for q in row))
def ints(row):
 vals=[q*D for q in row];assert all(q.denominator==1 for q in vals)
 return '#['+', '.join(str(q.numerator) for q in vals)+']'
s='import D4Bound.CensusArithmetic\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n/-! Generated by scripts/gen_census.py. Exact data, not accepted proof outcomes. -/\nnamespace D4Bound.CensusArithmetic\n'
s+=f'def denominator : ℤ := {D}\n'
for name,row in [('totalCoeffs',total),('countCoeffs',counts),('floorNumerators',floors),('surplusNumerators',surpluses)]:s+=f'def {name} : Array ℤ := {ints(row)}\n'
s+='def planeCoeffs : Array (Array ℤ) := #[\n'+',\n'.join(ints(r) for r in planes)+'\n]\n'
s+='end D4Bound.CensusArithmetic\n'
out=P/'lean/D4Bound/CensusData.lean'
a=argparse.ArgumentParser();a.add_argument('--check',action='store_true');args=a.parse_args()
if args.check:
 assert out.read_text()==s,'generated census data differs'
 print('PASS: generated census data matches exact inputs')
else:out.write_text(s);print(f'Wrote {out.name}: {len(s)} characters, denominator {len(str(D))} digits')
