"""Emit bounded-memory kernel proofs for every finite census block.

The generator supplies no accepted results: each block runs `decide +kernel`,
and the proved enumeration theorem assembles the blocks over the full domain.
"""
import argparse
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "D4Bound"


def generate(n):
    lines = [
        "import D4Bound.CensusCheck",
        "import Mathlib.Tactic.IntervalCases",
        "",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 0",
        "set_option Elab.async false",
        "",
        "/-! Generated by scripts/gen_census_proofs.py. Each block is checked by Lean. -/",
        "namespace D4Bound.CensusArithmetic",
        "",
    ]
    for n3 in range(min(n, 25) + 1):
        for n2 in range(min(n3, 24) + 1):
            lines.extend([
                f"private theorem block_{n}_{n3}_{n2} : atPair {n} {n3} {n2} test = true := by",
                "  decide +kernel",
                "",
            ])
    lines.extend([
        f"theorem census_N{n} : allAt {n} test = true := by",
        "  apply allAt_of_pairs",
        "  intro n3 h3 n2 h2",
        f"  change n3 ≤ {min(n, 25)} at h3",
        "  interval_cases n3",
    ])
    for n3 in range(min(n, 25) + 1):
        lines.extend([
            f"  · change n2 ≤ {min(n3, 24)} at h2",
            "    interval_cases n2",
        ])
        for n2 in range(min(n3, 24) + 1):
            lines.append(f"    · exact block_{n}_{n3}_{n2}")
    lines.extend(["", "end D4Bound.CensusArithmetic", ""])
    return "\n".join(lines)


def generate_large(n):
    """Keep both kernel reductions and the per-file proof environment small."""
    sources = {}
    imports = []
    for lo in range(0, min(n, 25) + 1, 8):
        name = f"CensusFinite{n:02d}Part{lo // 8}"
        imports.append(f"import D4Bound.{name}")
        lines = [
            "import D4Bound.CensusCheck",
            "import Mathlib.Tactic.IntervalCases",
            "set_option maxRecDepth 100000",
            "set_option maxHeartbeats 0",
            "set_option Elab.async false",
            "/-! Generated bounded-memory census blocks; each is checked by Lean. -/",
            "namespace D4Bound.CensusArithmetic",
        ]
        for n3 in range(lo, min(lo + 8, min(n, 25) + 1)):
            for n2 in range(min(n3, 24) + 1):
                for block in range(4):
                    lines += [
                        f"private theorem chunk_{n}_{n3}_{n2}_{block} :",
                        f"    atPairChunk {n} {n3} {n2} {block} test = true := by decide +kernel",
                    ]
                lines += [
                    f"theorem pair_{n}_{n3}_{n2} : atPair {n} {n3} {n2} test = true := by",
                    "  apply atPair_of_chunks (by decide)",
                    "  intro block hb",
                    "  interval_cases block",
                    *[f"  · exact chunk_{n}_{n3}_{n2}_{block}" for block in range(4)],
                ]
        lines += ["end D4Bound.CensusArithmetic", ""]
        sources[name] = "\n".join(lines)
    lines = imports + [
        "import Mathlib.Tactic.IntervalCases",
        "set_option maxHeartbeats 0",
        "set_option Elab.async false",
        "namespace D4Bound.CensusArithmetic",
        f"theorem census_N{n} : allAt {n} test = true := by",
        "  apply allAt_of_pairs",
        "  intro n3 h3 n2 h2",
        f"  change n3 ≤ {min(n, 25)} at h3",
        "  interval_cases n3",
    ]
    for n3 in range(min(n, 25) + 1):
        lines += [f"  · change n2 ≤ {min(n3, 24)} at h2", "    interval_cases n2"]
        lines += [f"    · exact pair_{n}_{n3}_{n2}" for n2 in range(min(n3, 24) + 1)]
    lines += ["end D4Bound.CensusArithmetic", ""]
    sources[f"CensusFinite{n:02d}"] = "\n".join(lines)
    return sources


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sources = {}
    for n in range(1, 27):
        if n <= 21:
            sources[f"CensusFinite{n:02d}"] = generate(n)
        else:
            sources.update(generate_large(n))
    for name, text in sources.items():
        path = TARGET / f"{name}.lean"
        if args.check:
            if path.read_text() != text:
                raise SystemExit(f"FAIL: generated census proof differs: {path.name}")
        else:
            path.write_text(text)
    print(f"PASS: {len(sources)} census proof sources match" if args.check else
          f"Wrote {len(sources)} census proof sources for all 26 nonzero count slices")


if __name__ == "__main__":
    main()
