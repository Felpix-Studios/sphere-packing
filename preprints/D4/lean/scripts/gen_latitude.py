def bernstein3(poly,lo,hi):
 d=3;w=hi-lo
 powers=[[Q(0)]*4 for _ in range(4)]
 for (i,j),a in poly.items():
  assert i<=3 and j<=3
  for k in range(i+1):
   for l in range(j+1):powers[k][l]+=a*math.comb(i,k)*math.comb(j,l)*lo**(i+j-k-l)*w**(k+l)
 vals=[[sum((powers[k][l]*Q(math.comb(i,k),math.comb(d,k))*Q(math.comb(j,l),math.comb(d,l)) for k in range(i+1) for l in range(j+1)),Q(0)) for j in range(4)]for i in range(4)]
 den=math.lcm(*(v.denominator for row in vals for v in row))
 return [[int(v*den) for v in row] for row in vals],den

def tree(p,depth=0):
 bounds={k:m.bounds(v) for k,v in p.items()}
 if bounds['D'][1]<0 or (bounds['P'][0]>=0 and bounds['V'][1]<=0) or (bounds['P'][0]>=0 and bounds['H'][0]>=0) or (bounds['V'][1]<=0 and bounds['H'][1]<=0):return None
 assert depth<100
 pair={k:m.split(v,depth%2) for k,v in p.items()}
 return (depth%2, tree({k:v[0] for k,v in pair.items()},depth+1),tree({k:v[1] for k,v in pair.items()},depth+1))

def vec(v):return '⟨'+', '.join(map(str,v))+'⟩'
def matrix(v):return '⟨'+', '.join(vec(r) for r in v)+'⟩'
def rat(q):return f'({q.numerator} / {q.denominator} : ℚ)'
def size(t):return 1 if t is None else 1+size(t[1])+size(t[2])

def emit_tree(t,prefix,defs):
 if t is None:return '.leaf'
 children=[]
 for j in [1,2]:
  u=t[j]
  if size(u)>160:
   name=prefix+str(j);e=emit_tree(u,name,defs);defs.append(f'def {name} : Tree := {e}\n');children.append(name)
  else:
   def expr(v):return '.leaf' if v is None else f'(.{"x" if v[0]==0 else "y"} {expr(v[1])} {expr(v[2])})'
   children.append(expr(u))
 return f'(.{"x" if t[0]==0 else "y"} {children[0]} {children[1]})'

