"""Generate D4Bound/ScalarData.lean from ../../data/v7/scalar.json.

The Lean file holds:
  * Fq, Gq: the 50 rational coefficients of F and G, copied verbatim from scalar.json;
  * FZ, DF and GZ, DG: integer coefficient lists and denominators with Fq = FZ/DF, Gq = GZ/DG;
  * a positivity certificate for G on [0, oo) and for -F on [49/8, oo).

A certificate is a chain of dyadic intervals [A/2^k, (A+h)/2^k] that tiles [lo, S), plus a
tail shift S. On each interval Lean computes the integer polynomial
Q(w) = 2^(k n) P((A + w)/2^k) and checks a lower bound for Q on [0, h] (function `lb`);
on [S, oo) it checks that every coefficient of P(S + w) is positive.

This script only searches for the intervals. Lean recomputes every check in the kernel.

It writes two files: D4Bound/ScalarData.lean (the data) and D4Bound/ScalarCert.lean (one kernel
check per chunk of CHUNK intervals, so that no single declaration needs much memory).

Usage (from the lean/ folder):
  python3 scripts/gen_scalar.py           # write both files
  python3 scripts/gen_scalar.py --check   # exit 1 unless the files on disk are what we would write
"""
import json
import sys
from fractions import Fraction as Q
from math import lcm
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parent
DATA = LEAN.parent / "data" / "v7" / "scalar.json"
OUT = LEAN / "D4Bound" / "ScalarData.lean"
OUT_CERT = LEAN / "D4Bound" / "ScalarCert.lean"
CHUNK = 8


def comp(P, A, D):
    """Coefficients in w of D^(n) P((A + w)/D), n = len(P) - 1, by the same recursion as Lean."""
    q = []
    for i in range(len(P) - 1, -1, -1):
        m = len(P) - 1 - i  # length of the tail after P[i]
        nq = [0] * (len(q) + 1)
        for j, c in enumerate(q):
            nq[j] += A * c
            nq[j + 1] += c
        nq[0] += P[i] * D**m
        q = nq if q else [P[i] * D**m]
    return q


def lb(h, q):
    v = 0
    for c in reversed(q):
        v = c + h * min(v, 0)
    return v


def leaf_ok(P, A, k, h):
    return lb(h, comp(P, A, 2**k)) > 0


def cover(P, a, ka, S, hmax_exp=12, maxk=40):
    """Greedy chain of leaves (A, k, h) from a/2^ka up to S (an integer)."""
    leaves = []
    pos = Q(a, 2**ka)
    end = Q(S)
    while pos < end:
        k = 0
        while (pos * 2**k).denominator != 1:
            k += 1
        while True:
            A = int(pos * 2**k)
            best = None
            h = 1
            while Q(A + h, 2**k) <= end and h <= 2 ** (hmax_exp + k) and leaf_ok(P, A, k, h):
                best = h
                h *= 2
            if best:
                leaves.append((A, k, best))
                pos = Q(A + best, 2**k)
                break
            k += 1
            if k > maxk:
                raise SystemExit(f"no leaf found at {pos}")
    return leaves


def tail_ok(P, S):
    q = comp(P, S, 1)
    return len(q) > 0 and all(c > 0 for c in q)


def lean_list(xs):
    return "[" + ",\n  ".join(xs) + "]"


def main():
    d = json.loads(DATA.read_text())
    Fs, Gs = d["F"], d["G"]
    F = [Q(x) for x in Fs]
    G = [Q(x) for x in Gs]
    DF = lcm(*[x.denominator for x in F])
    DG = lcm(*[x.denominator for x in G])
    FZ = [int(x * DF) for x in F]
    GZ = [int(x * DG) for x in G]
    negFZ = [-c for c in FZ]
    SG, SF = 256, 128
    assert tail_ok(GZ, SG) and tail_ok(negFZ, SF)
    LG = cover(GZ, 0, 0, SG)
    LF = cover(negFZ, 49, 3, SF)

    def leaves(L):
        return "[" + ",\n  ".join(f"({A}, {k}, {h})" for A, k, h in L) + "]"

    def qlit(s):
        return f"({s} : ℚ)" if "/" not in s else f"({s.split('/')[0]} / {s.split('/')[1]} : ℚ)"

    text = f"""/-
Generated by scripts/gen_scalar.py from data/v7/scalar.json. Do not edit by hand.
-/
import Mathlib.Data.Rat.Defs

/-!
# Data of the scalar function

`Fq` and `Gq` are the coefficients of `F` and `G` (constant term first), copied from
`data/v7/scalar.json`. `FZ / DF` and `GZ / DG` are the same lists with a common denominator.
`certG` and `certF` are chains of dyadic intervals `[A/2^k, (A+h)/2^k]`, given as `(A, k, h)`,
found by `scripts/gen_scalar.py`; `Scalar.lean` checks them in the kernel.
-/

namespace D4Bound

/-- Coefficients of `F`, constant term first. -/
def Fq : List ℚ := {lean_list([qlit(s) for s in Fs])}

/-- Coefficients of `G`, constant term first. -/
def Gq : List ℚ := {lean_list([qlit(s) for s in Gs])}

/-- Common denominator of `Fq`. -/
def DF : ℕ := {DF}

/-- Common denominator of `Gq`. -/
def DG : ℕ := {DG}

/-- `DF * Fq`. -/
def FZ : List ℤ := {lean_list([str(c) for c in FZ])}

/-- `DG * Gq`. -/
def GZ : List ℤ := {lean_list([str(c) for c in GZ])}

/-- Intervals covering `[0, {SG})` for `G`. -/
def certG : List (ℕ × ℕ × ℕ) := {leaves(LG)}

/-- Intervals covering `[49/8, {SF})` for `-F`. -/
def certF : List (ℕ × ℕ × ℕ) := {leaves(LF)}

end D4Bound
"""
    def chunks(name, P, L, a0, k0, S):
        out = []
        starts = []
        for i in range(0, len(L), CHUNK):
            starts.append(i)
        names = []
        for c, i in enumerate(starts):
            sa, ska = (a0, k0) if i == 0 else (L[i][0], L[i][1])
            if i + CHUNK < len(L):
                eb, ekb = L[i + CHUNK][0], L[i + CHUNK][1]
            else:
                eb, ekb = S, 0
            nm = f"{name}_chunk_{c}"
            names.append(nm)
            out.append(
                f"theorem {nm} :\n    PosOn {P} ((({sa} : ℕ) : ℝ) / 2 ^ ({ska} : ℕ)) ((({eb} : ℕ) : ℝ) / 2 ^ ({ekb} : ℕ)) :=\n"
                f"  chainOK_sound _ _ _ _ _ _ (by decide +kernel :\n"
                f"    chainOK {P} {sa} {ska} ((cert{name}.drop {i}).take {CHUNK}) {eb} {ekb} = true)\n")
        chain = names[-1]
        for nm in reversed(names[:-1]):
            chain = f"{nm}.trans ({chain})" if chain != names[-1] else f"{nm}.trans {chain}"
        return "\n".join(out), chain, (a0, k0)

    gtext, gchain, gst = chunks("G", "GZ", LG, 0, 0, SG)
    ftext, fchain, fst = chunks("F", "negFZ", LF, 49, 3, SF)
    cert_text = f"""/-
Generated by scripts/gen_scalar.py from data/v7/scalar.json. Do not edit by hand.
-/
import D4Bound.ScalarCheck

/-!
# Kernel checks of the scalar certificate

Each theorem below runs `chainOK` on a chunk of the interval lists in `ScalarData.lean`, by
`decide +kernel` (exact integer arithmetic in the Lean kernel, no `native_decide`).
Asynchronous elaboration is off so that the chunks are checked one at a time; with it on, the
chunks run concurrently and peak memory grows to several GB.
-/

set_option Elab.async false

namespace D4Bound

/-- `-F`, scaled: `negFZ = -DF * Fq`. -/
def negFZ : List ℤ := FZ.map (- ·)

{gtext}
/-- `G > 0` on `[0, {SG})`. -/
theorem G_cover : PosOn GZ (((0 : ℕ) : ℝ) / 2 ^ (0 : ℕ)) ((({SG} : ℕ) : ℝ) / 2 ^ (0 : ℕ)) :=
  {gchain}

/-- All coefficients of `G({SG} + w)` are positive. -/
theorem G_tail : tailOK GZ {SG} = true := by decide +kernel

{ftext}
/-- `-F > 0` on `[49/8, {SF})`. -/
theorem F_cover : PosOn negFZ (((49 : ℕ) : ℝ) / 2 ^ (3 : ℕ)) ((({SF} : ℕ) : ℝ) / 2 ^ (0 : ℕ)) :=
  {fchain}

/-- All coefficients of `-F({SF} + w)` are positive. -/
theorem F_tail : tailOK negFZ {SF} = true := by decide +kernel

end D4Bound
"""
    if "--check" in sys.argv:
        if OUT.read_text() != text or OUT_CERT.read_text() != cert_text:
            print("FAIL: ScalarData.lean or ScalarCert.lean differs from the generated text")
            sys.exit(1)
        print(f"PASS: ScalarData.lean and ScalarCert.lean match (certG {len(LG)} leaves, certF {len(LF)} leaves)")
        return
    OUT.write_text(text)
    OUT_CERT.write_text(cert_text)
    print(f"wrote {OUT.name} and {OUT_CERT.name} (certG {len(LG)} leaves, certF {len(LF)} leaves)")


if __name__ == "__main__":
    main()
