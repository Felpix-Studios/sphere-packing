"""Emit exact degree-12 affine power-to-Bernstein matrices and algebraic proofs."""
from pathlib import Path
from fractions import Fraction as Q
import argparse, importlib.util, sys
sys.dont_write_bytecode=True
PKG=Path(__file__).resolve().parents[2]
SRC=PKG/'verify/stage1_v7/record/current/base/new_work/spherical_sdp'
sp=importlib.util.spec_from_file_location('certify',SRC/'certify.py')
m=importlib.util.module_from_spec(sp);sp.loader.exec_module(m)
lines=['-- Generated by gen_spherical_affine.py. Matrix identities are proved in Lean.',
       'import D4Bound.SphericalSignTransform','set_option maxHeartbeats 0',
       'set_option Elab.async false','namespace D4Bound.SphericalSign.Bernstein']
for n,p,q in [(24,603,400),(25,303,200),(26,61,40)]:
    T,d=m.transform(12,Q(-1),Q(p,q))
    mat='!['+', '.join('!['+', '.join(str(int(v)) for v in row)+']' for row in T)+']'
    lines.extend([f'def affine{n} : I → I → ℤ := {mat}',f'def affineDen{n} : ℤ := {d}',
       f'''lemma affine{n}_exact (j : I) (x : ℝ) :
    (∑ i : I,(affine{n} i j:ℝ)*basis i x)=(affineDen{n}:ℝ)*(-1+({p}:ℝ)/{q}*x)^j.val := by
  fin_cases j <;> norm_num [affine{n},affineDen{n},basis,Fin.sum_univ_succ,Nat.choose] <;> ring''',
       f'#print axioms affine{n}_exact'])
lines.append('end D4Bound.SphericalSign.Bernstein')
text='\n\n'.join(lines)+'\n';path=PKG/'lean/D4Bound/SphericalSignAffine.lean'
ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
if args.check:assert path.read_text()==text
else:path.write_text(text)
print('PASS generated exact affine matrices; Lean compile required.',len(text))
