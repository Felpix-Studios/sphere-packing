"""Emit nested-array storage for the included spherical Bernstein tensors.

The source literals are untrusted data. Lean checks every coefficient equality
against the original tensor definitions; no Python acceptance flag is imported.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    source = (ROOT / "D4Bound/SphericalSignTensorData.lean").read_text()
    definitions = {}
    for line in source.splitlines():
        for prefix in ("upper", "gramUpper"):
            for n in (24, 25, 26):
                name = f"{prefix}{n}"
                start = f"def {name} : Tensor := "
                if line.startswith(start):
                    value = line[len(start):]
                    if not value.startswith("!["):
                        raise ValueError(f"expected nested vector literal for {name}")
                    if name in definitions:
                        raise ValueError(f"duplicate tensor {name}")
                    definitions[name] = value.replace("![", "#[")
    if len(definitions) != 6:
        raise ValueError("missing spherical tensor input")
    out = [
        "-- Generated by scripts/gen_spherical_array_data.py.",
        "import D4Bound.SphericalSignArray",
        "import D4Bound.SphericalSignTensorData",
        "set_option maxHeartbeats 0",
        "set_option maxRecDepth 20000",
        "set_option Elab.async false",
        "namespace D4Bound.SphericalSign.Bernstein.ArrayData",
    ]
    for name, value in definitions.items():
        out += [
            f"def {name}Data : Data := {value}",
            f"private theorem {name}_coefficients : ∀ i j k,",
            f"    tensor {name}Data i j k = {name} i j k := by decide +kernel",
            f"theorem {name}_eq : tensor {name}Data = {name} := by",
            "  funext i j k",
            f"  exact {name}_coefficients i j k",
        ]
    out += ["end D4Bound.SphericalSign.Bernstein.ArrayData", ""]
    return "\n\n".join(out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "D4Bound/SphericalSignArrayData.lean"
    text = generate()
    if args.check:
        if output.read_text() != text:
            raise SystemExit("FAIL: spherical array source differs")
        print("PASS: spherical array source matches; Lean equality checks are separate")
    else:
        output.write_text(text)
        print("Wrote six array tensors and their Lean equality checks")
