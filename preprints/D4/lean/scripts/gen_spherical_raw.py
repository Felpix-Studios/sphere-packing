def render(x):
    if isinstance(x,list):
        return '['+', '.join(map(render,x))+']'
    return str(int(x))

def emit(path,lines,check):
    text='\n\n'.join(lines)+'\n'
    assert len(text.encode())<1024**2, (path,len(text))
    if check:
        assert path.read_text()==text,path
    else:
        path.write_text(text)
    print(path.name,len(text),flush=True)

