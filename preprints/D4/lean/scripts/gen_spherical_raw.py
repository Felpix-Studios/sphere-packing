def add(n, p, q):
    if n == 0:
        return p+q
    return [add(n-1,p[i],q[i]) if i<len(p) and i<len(q)
            else p[i] if i<len(p) else q[i] for i in range(max(len(p),len(q)))]

def mul(n,p,q):
    if n == 0:
        return p*q
    v=[]
    for a in reversed(p):
        v=add(n,[mul(n-1,a,b) for b in q],[(0 if n==1 else [])]+v)
    return v

def smul(n,a,p):
    return a*p if n==0 else [smul(n-1,a,q) for q in p]

