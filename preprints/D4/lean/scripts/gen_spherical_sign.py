"""Generate kernel-checkable univariate signs for the three included spherical certificates.
This untrusted generator exports coefficients and full dyadic trees; Lean checks their signs.
Polynomial-to-Gram expansion is a separate obligation of the spherical energy interface.
"""
from pathlib import Path
from fractions import Fraction as Q
import argparse,importlib.util,json,math,sys
sys.dont_write_bytecode=True
PKG=Path(__file__).resolve().parents[2]
SRC=PKG/'verify/stage1_v7/record/current/base/new_work/spherical_sdp'
sp=importlib.util.spec_from_file_location('spherical_certify',SRC/'certify.py');m=importlib.util.module_from_spec(sp);sp.loader.exec_module(m)
def comp(A,D,P):
 d=len(P)-1
 return [sum(P[i]*math.comb(i,j)*A**(i-j)*D**(d-i) for i in range(j,len(P))) for j in range(len(P))]
def normalized(p,q,P):return [-v*(p+q)**j for j,v in enumerate(comp(-q,q,P))]
def lb(P):
 v=0
 for c in reversed(P):v=c+min(v,0)
 return v
def tree(P,a=0,k=0):
 if lb(comp(a,2**k,P))>=0:return None
 assert k<60
 return (tree(P,2*a,k+1),tree(P,2*a+1,k+1))
def expr(t):return '.leaf' if t is None else f'(.split {expr(t[0])} {expr(t[1])})'
def size(t):return 1 if t is None else 1+size(t[0])+size(t[1])
lines=['-- Generated by scripts/gen_spherical_sign.py; exact coefficients and dyadic trees.',
'import D4Bound.SphericalSignCheck','set_option Elab.async false','set_option maxRecDepth 10000','set_option maxHeartbeats 0','namespace D4Bound.SphericalSign']
for N,fn in [(24,'s05075_taper12_exact.json'),(25,'s0515_count25_exact.json'),(26,'s0525_count26_exact.json')]:
 d=json.loads((SRC/fn).read_text());tri,td,pair,pd,gram,obj,s=m.polynomials(d)
 assert Q(d['uniform_repair']['pair_shift'])==0
 qcoeff=list(map(Q,d['uniform_repair']['gegenbauer_coefficients']));qpoly=[Q(0)]*len(qcoeff)
 for ell,a in enumerate(qcoeff):
  for j in range(ell//2+1):qpoly[ell-2*j]+=a*Q((-1)**j*math.comb(ell-j,j)*2**(ell-2*j),ell+1)
 while len(qpoly)>1 and qpoly[-1]==0:qpoly.pop()
 qd=math.lcm(*(v.denominator for v in qpoly));qpoly=[int(v*qd) for v in qpoly]
 for label,P,den in [('pair',list(map(int,pair)),pd),('repair',qpoly,qd)]:
  name=f'{label}{N}';T=tree(normalized(s.numerator,s.denominator,P))
  print(name,'degree',len(P)-1,'nodes',size(T))
  lines += [f'def {name} : List ℤ := {P}',f'def {name}Den : ℤ := {den}',f'def {name}Tree : Tree := {expr(T)}',
    f'theorem {name}_checked : check (normalized {s.numerator} {s.denominator} {name}) 0 0 {name}Tree = true := by decide +kernel',
    f'theorem {name}_nonpos (t : ℝ) (hlo : -1 ≤ t) (hhi : t ≤ {s.numerator}/{s.denominator}) : evalZ {name} t ≤ 0 :=\n  raw_nonpos_of_checked {name} {s.numerator} {s.denominator} (by norm_num) (by norm_num) {name}Tree {name}_checked t hlo hhi',
    f'#print axioms {name}_nonpos']
lines += ['end D4Bound.SphericalSign',''];text='\n\n'.join(lines)
p=PKG/'lean/D4Bound/SphericalSignData.lean';ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
if a.check:assert p.read_text()==text
else:p.write_text(text)
print('PASS: spherical univariate certificate generation',len(text))
