"""Generate exact physical-kernel pair identities, checked coefficientwise in Lean."""
from pathlib import Path
from fractions import Fraction as Q
import argparse
import ast
import math

PKG = Path(__file__).resolve().parents[2]
OUT = PKG/'lean/D4Bound'
ap = argparse.ArgumentParser()
ap.add_argument('--check',action='store_true')
ap.add_argument('--index',type=int,choices=range(3))
args = ap.parse_args()


def value(text,name,typ):
    return ast.literal_eval(text.split(f'def {name} : {typ} := ')[1].split('\n')[0])


def convolution(a,b):
    out=[0]*(len(a)+len(b)-1)
    for i,x in enumerate(a):
        for j,y in enumerate(b):out[i+j]+=x*y
    return out


for i,s in enumerate([Q(251467,500000),Q(21,40),Q(103,200)]):
    if args.index is not None and i != args.index:
        continue
    d = (OUT/f'SphericalSurplusSignData{i}.lean').read_text()
    corr = value(d,f'correction{i}','List ℤ')
    cd = value(d,f'correctionDen{i}','ℤ')
    od = value(d,f'originDen{i}','ℤ')
    v = value(d,f'vNum{i}','ℤ')
    b = value(d,f'bNum{i}','ℤ')
    m = value(d,f'countM{i}','ℕ')
    eta = Q(1,1000000)
    correction = [(2-2*m)*Q(c,cd) for c in corr]
    correction[0] += Q(2*v+b,od**2)-eta
    extra_den = math.lcm(*(x.denominator for x in correction))
    extra = [int(x*extra_den) for x in correction]
    # Independently reconstruct the exact diagonal/coupling power coefficients.
    rays=ast.literal_eval(d.split(f'def rays{i} : List Ray := ')[1].split('\n\n')[0].replace('⟨','[').replace('⟩',']'))
    fd=value(d,f'featureDen{i}','ℤ')
    sd=value(d,f'scalarPowerDen{i}','ℤ')
    scalar=value(d,f'scalarPower{i}','List ℤ')
    pair_text=(OUT/f'SphericalSurplusSignPair{i}.lean').read_text()
    pair=value(pair_text,f'pair{i}','List ℤ')
    pd=value(pair_text,f'pairDen{i}','ℤ')
    reconstructed=[Q(c,sd) for c in scalar]+[Q(0)]*(len(pair)-len(scalar))
    for ell,origin,c in rays:
        diagonal=[0]*(2*ell+1)
        for j in range(ell+1):diagonal[2*j]=(-1)**j*math.comb(ell,j)
        for j,z in enumerate(convolution(convolution(c,c),diagonal)):
            reconstructed[j]+=Q(z,fd**2)
        if ell==0:
            for j,z in enumerate(c):reconstructed[j]+=Q(2*origin*z,od*fd)
    for j,c in enumerate(correction):reconstructed[j]+=c
    assert reconstructed==[Q(c,pd) for c in pair],i
    expr=f'''(g{i} x + 2*coupling{i} x + kernel{i} x x 1)'''
    text=f'''-- Generated by gen_spherical_surplus_pair.py; kernel checks all coefficients.
import D4Bound.SphericalSurplusSignPairBasic
import D4Bound.SphericalSurplusSignData{i}
import D4Bound.SphericalSurplusSignPair{i}
set_option maxHeartbeats 0
set_option maxRecDepth 20000
set_option Elab.async false
namespace D4Bound.SphericalSurplusSign
open SphericalSign

def pairCorrection{i} : List ℤ := {extra}
def pairCorrectionDen{i} : ℤ := {extra_den}

theorem pairCorrection{i}_value (x : ℝ) :
    evalZ pairCorrection{i} x/pairCorrectionDen{i} =
      2*v{i}+b{i}+(2-2*(countM{i}:ℝ))*F{i} x-(eta{i}:ℝ) := by
  norm_num [pairCorrection{i},pairCorrectionDen{i},v{i},b{i},F{i},countM{i},
    vNum{i},bNum{i},originDen{i},correction{i},correctionDen{i},eta{i},evalZ]
  ring

theorem pair{i}_identity :
    pair{i}.map ((scalarPowerDen{i}*originDen{i}*featureDen{i}^2*pairCorrectionDen{i})*·) =
      (correctedPairNum scalarPower{i} pairCorrection{i} rays{i} scalarPowerDen{i}
        originDen{i} featureDen{i} pairCorrectionDen{i}).map (pairDen{i}*·) := by decide +kernel

theorem rawPair{i}_le (x : ℝ) (hlo : -1≤x) (hhi : x≤{s.numerator}/{s.denominator}) :
    {expr} ≤ (eta{i}:ℝ) := by
  have h := corrected_pair_nonpos scalarPower{i} pairCorrection{i} pair{i} rays{i}
    scalarPowerDen{i} originDen{i} featureDen{i} pairCorrectionDen{i} pairDen{i}
    (by norm_num [scalarPowerDen{i}]) (by norm_num [originDen{i}])
    (by norm_num [featureDen{i}]) (by norm_num [pairCorrectionDen{i}])
    (by norm_num [pairDen{i}]) pair{i}_identity x (pair{i}_nonpos x hlo hhi)
  rw [pairCorrection{i}_value] at h
  dsimp [g{i},coupling{i},kernel{i}]
  linarith

#print axioms rawPair{i}_le
end D4Bound.SphericalSurplusSign
'''
    if i == 1:
        # The unrestricted certificate has zero physical correction, so
        # norm_num closes this identity without any residual ring goal.
        text = text.replace('\n  ring\n', '\n')
    path=OUT/f'SphericalSurplusSignPairLink{i}.lean'
    if args.check:
        assert path.read_text()==text
    else:
        path.write_text(text)
    print(path.name,len(text))
