"""Export untrusted exact pair sign data for the three ANGULAR surplus proofs.

Lean checks every complete dyadic tree. The separate raw-kernel linkage is not
asserted by this generator or by its numerical inputs.
"""
from pathlib import Path
from fractions import Fraction as Q
import argparse
import importlib.util
import json
import math
import sys

sys.dont_write_bytecode = True
PKG = Path(__file__).resolve().parents[2]
SOURCE = PKG / 'verify/stage2_origin/source'


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def comp(a, d, p):
    degree = len(p)-1
    return [sum(p[i]*math.comb(i,j)*a**(i-j)*d**(degree-i)
                for i in range(j,len(p))) for j in range(len(p))]


def normalized(p, q, coeffs):
    return [-v*(p+q)**j for j,v in enumerate(comp(-q,q,coeffs))]


def lb(p):
    value = 0
    for c in reversed(p):
        value = c+min(value,0)
    return value


def tree(p, a=0, k=0, budget=None):
    budget[0] += 1
    assert budget[0] <= 20000 and k <= 60, 'bounded diagnostic exhausted'
    if lb(comp(a,2**k,p)) >= 0:
        return None
    return tree(p,2*a,k+1,budget), tree(p,2*a+1,k+1,budget)


def expr(t):
    return '.leaf' if t is None else f'(.split {expr(t[0])} {expr(t[1])})'


parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
fixed = load('fixed_surplus_sign', SOURCE / 'target625/geometry/fixed_cardinality_spherical_algebra.py')
ordinary = load('ordinary_surplus_sign', SOURCE / 'optimization/continuation_20261018/base/new_work/spherical_sdp/certify.py')
registry = json.loads((SOURCE / 'target625/origin_completion/FINAL_ORIGIN_REGISTRY.json').read_text())
for i, item in enumerate(registry['common_g_certificates']):
    data = json.loads((SOURCE / item['certificate']).read_text())
    algebra = fixed if data.get('fixed_count') else ordinary
    _, _, pair, den, _, _, cutoff = algebra.polynomials(data)
    repair = data.get('repair', data.get('bounded_cardinality_common_g_repair'))
    eta = Q(repair['pair_shift'])
    new_den = math.lcm(den, eta.denominator)
    pair = [int(v)*(new_den//den) for v in pair]
    pair[0] -= int(eta*new_den)
    budget = [0]
    witness = tree(normalized(cutoff.numerator,cutoff.denominator,pair),budget=budget)
    text = f'''-- Generated by gen_spherical_surplus_sign.py; checked data, not a raw-kernel linkage.
import D4Bound.SphericalSignData
set_option maxHeartbeats 0
set_option maxRecDepth 20000
set_option Elab.async false
namespace D4Bound.SphericalSurplusSign
open SphericalSign

def pair{i} : List ℤ := {pair}
def pairDen{i} : ℤ := {new_den}
def pairTree{i} : Tree := {expr(witness)}

theorem pair{i}_checked :
    check (normalized {cutoff.numerator} {cutoff.denominator} pair{i}) 0 0 pairTree{i} = true := by
  decide +kernel

theorem pair{i}_nonpos (t : ℝ) (hlo : -1 ≤ t) (hhi : t ≤ {cutoff.numerator}/{cutoff.denominator}) :
    evalZ pair{i} t ≤ 0 :=
  raw_nonpos_of_checked pair{i} {cutoff.numerator} {cutoff.denominator} (by norm_num) (by norm_num)
    pairTree{i} pair{i}_checked t hlo hhi

theorem repair{i}_nonpos (t : ℝ) (hlo : -1 ≤ t) (hhi : t ≤ {cutoff.numerator}/{cutoff.denominator}) :
    evalZ repair26 t ≤ 0 :=
  repair26_nonpos t hlo (by linarith)

#print axioms pair{i}_nonpos
#print axioms repair{i}_nonpos
end D4Bound.SphericalSurplusSign
'''
    assert len(text.encode()) < 1024**2
    output = PKG / f'lean/D4Bound/SphericalSurplusSignPair{i}.lean'
    if args.check:
        assert output.read_text() == text, output
    else:
        output.write_text(text)
    print(i, 'pair degree',len(pair)-1,'complete nodes',budget[0], 'bytes', len(text), flush=True)
print('PASS generation consistency only; Lean replay and raw-kernel linkage required.')
